    private static final int MAX_BODY_BYTES = 4096;
    private static final long BUDGET_NANOS = Duration.ofSeconds(30).toNanos();
    private static final List<java.lang.String> HEADERS = List.of("X-Content-Type-Options", "X-Frame-Options", "X-XSS-Protection");

