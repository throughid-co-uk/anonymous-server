    @Test
    void observesTheRunningServer() throws java.lang.Exception {
        // On the candidate the baseline's exact request list (FactoryHttpParityRequests, written by the Factory after the
        // baseline runs); on the baseline the plan derived from the application's handler mappings.
        String[] recorded = recordedRequests();
        List<HttpParityPlan.Request> requests = recorded != null ? HttpParityPlan.fromLines(recorded)
                : HttpParityPlan.plan(inventory(), graphqlPath());
        java.lang.String port = factoryParityEnvironment.getProperty("local.server.port");
        Path out = Paths.get(java.lang.System.getProperty("factory.behavior.out"));
        Files.createDirectories(out);
        // The probe's own result, read by the Factory: "completed" only once every request is written.
        Path status = out.resolve("factory-http-parity.status");
        Files.write(status, "started\n".getBytes(StandardCharsets.UTF_8));
        HttpClient client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(5))
                .followRedirects(HttpClient.Redirect.NEVER).build();
        long deadline = java.lang.System.nanoTime() + BUDGET_NANOS;
        int index = 0;
        for (HttpParityPlan.Request request : requests) {
            java.lang.String observed;
            long left = deadline - java.lang.System.nanoTime();
            if (left <= 0) {
                observed = errorDocument(request, "not sent: the " + 30 + " s budget was used");
            } else {
                observed = send(client, port, request, Duration.ofNanos(java.lang.Math.min(left, Duration.ofSeconds(10).toNanos())));
            }
            java.lang.String json = "{\"case\":" + quote(request.caseId) + ",\"obligation\":\"factory-http-parity\",\"observed\":"
                    + quote(observed) + "}";
            Files.write(out.resolve(java.lang.String.format("factory-http-parity-%03d.json", index++)),
                    json.getBytes(StandardCharsets.UTF_8));
        }
        Files.write(status, ("completed " + index + "\n").getBytes(StandardCharsets.UTF_8));
    }

    private List<HttpParityPlan.Mapping> inventory() {
        List<HttpParityPlan.Mapping> mappings = new ArrayList<HttpParityPlan.Mapping>();
        for (RequestMappingHandlerMapping handlerMapping
                : factoryParityContext.getBeansOfType(RequestMappingHandlerMapping.class).values()) {
            for (Map.Entry<RequestMappingInfo, org.springframework.web.method.HandlerMethod> entry
                    : handlerMapping.getHandlerMethods().entrySet()) {
                RequestMappingInfo info = entry.getKey();
                Set<java.lang.String> methods = new TreeSet<java.lang.String>();
                for (RequestMethod method : info.getMethodsCondition().getMethods()) {
                    methods.add(method.name());
                }
                boolean readsBody = false;
                for (org.springframework.core.MethodParameter parameter : entry.getValue().getMethodParameters()) {
                    readsBody |= parameter.hasParameterAnnotation(org.springframework.web.bind.annotation.RequestBody.class);
                }
                for (java.lang.String pattern : info.getPatternValues()) {
                    mappings.add(new HttpParityPlan.Mapping(pattern, methods, readsBody));
                }
            }
        }
        return mappings;
    }

    // The baseline's request list, on the candidate: read from the exact path the Factory passes and checked against the
    // sha256 it recorded. Without the property (the baseline) there is none and the inventory is derived.
    private static java.lang.String[] recordedRequests() throws java.lang.Exception {
        java.lang.String path = java.lang.System.getProperty("factory.behavior.parityRequests");
        if (path == null) {
            return null;
        }
        byte[] bytes = Files.readAllBytes(Paths.get(path));
        java.lang.String expected = java.lang.System.getProperty("factory.behavior.parityRequestsSha256");
        if (expected == null || !expected.equals(sha256(bytes, bytes.length))) {
            throw new java.lang.IllegalStateException("The parity request list " + path + " does not have its recorded sha256");
        }
        return HttpParityPlan.readRequests(new java.lang.String(bytes, StandardCharsets.UTF_8)).toArray(new java.lang.String[0]);
    }

    private java.lang.String graphqlPath() {
        if (!org.springframework.util.ClassUtils.isPresent("graphql.GraphQL", getClass().getClassLoader())) {
            return null;
        }
        java.lang.String path = factoryParityEnvironment.getProperty("spring.graphql.http.path",
                factoryParityEnvironment.getProperty("spring.graphql.path",
                        factoryParityEnvironment.getProperty("dgs.graphql.path", "/graphql")));
        return path.startsWith("/") ? path : "/" + path;
    }

    private static java.lang.String send(HttpClient client, java.lang.String port, HttpParityPlan.Request request, Duration timeout) {
        try {
            HttpRequest.Builder builder = HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + request.path))
                    .timeout(timeout);
            if (request.body == null) {
                builder.method(request.method, HttpRequest.BodyPublishers.noBody());
            } else {
                builder.header("Content-Type", "application/json")
                        .method(request.method, HttpRequest.BodyPublishers.ofString(request.body));
            }
            HttpResponse<InputStream> response = client.send(builder.build(), HttpResponse.BodyHandlers.ofInputStream());
            byte[] bytes;
            boolean truncated;
            try (InputStream in = response.body()) {
                bytes = in.readNBytes(MAX_BODY_BYTES + 1);
            }
            truncated = bytes.length > MAX_BODY_BYTES;
            int length = java.lang.Math.min(bytes.length, MAX_BODY_BYTES);
            Optional<java.lang.String> contentType = response.headers().firstValue("Content-Type");
            // A non-text body is recorded as its length and sha256, never as escaped bytes.
            String binary = contentType.isPresent() && !text(contentType.get()) ? length + (truncated ? "+" : "")
                    + " bytes, sha256 " + sha256(bytes, length) : null;
            java.lang.String body = binary != null ? "" : new java.lang.String(bytes, 0, length, StandardCharsets.UTF_8);
            Map<java.lang.String, java.lang.String> compared = new TreeMap<java.lang.String, java.lang.String>();
            for (java.lang.String name : HEADERS) {
                Optional<java.lang.String> value = response.headers().firstValue(name);
                if (value.isPresent()) {
                    compared.put(name, value.get());
                }
            }
            java.lang.StringBuilder headers = new java.lang.StringBuilder("{");
            for (Map.Entry<java.lang.String, java.lang.String> e : compared.entrySet()) {
                headers.append(headers.length() > 1 ? "," : "").append(quote(e.getKey())).append(':').append(quote(e.getValue()));
            }
            headers.append('}');
            Optional<java.lang.String> type = response.headers().firstValue("Content-Type");
            return "{\"method\":" + quote(request.method) + ",\"path\":" + quote(request.path)
                    + ",\"status\":" + response.statusCode() + ",\"type\":" + (type.isPresent() ? quote(type.get()) : "null")
                    + ",\"auth\":" + response.headers().firstValue("WWW-Authenticate").isPresent() + ",\"headers\":"
                    + headers + ",\"body\":" + quote(body) + (binary == null ? "" : ",\"binary\":" + quote(binary))
                    + ",\"truncated\":" + truncated + "}";
        } catch (java.lang.InterruptedException e) {
            java.lang.Thread.currentThread().interrupt();
            return errorDocument(request, e.getClass().getName());
        } catch (java.lang.Exception e) {
            return errorDocument(request, e.getClass().getName());
        }
    }

    // A request that failed as a request: its method and path (so the Factory replays it) and the error.
    private static java.lang.String errorDocument(HttpParityPlan.Request request, java.lang.String error) {
        return "{\"method\":" + quote(request.method) + ",\"path\":" + quote(request.path) + ",\"error\":" + quote(error) + "}";
    }

    private static boolean text(java.lang.String contentType) {
        java.lang.String type = contentType.toLowerCase(java.util.Locale.ROOT);
        return type.startsWith("text/") || type.contains("json") || type.contains("xml") || type.contains("javascript")
                || type.contains("x-www-form-urlencoded") || type.contains("graphql");
    }

    private static java.lang.String sha256(byte[] bytes, int length) throws java.security.NoSuchAlgorithmException {
        byte[] digest = java.security.MessageDigest.getInstance("SHA-256").digest(java.util.Arrays.copyOf(bytes, length));
        java.lang.StringBuilder hex = new java.lang.StringBuilder();
        for (byte b : digest) {
            hex.append(java.lang.String.format("%02x", b));
        }
        return hex.toString();
    }

    private static java.lang.String quote(java.lang.String text) {
        java.lang.StringBuilder out = new java.lang.StringBuilder("\"");
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '"' || c == '\\') {
                out.append('\\').append(c);
            } else if (c < 0x20) {
                out.append(java.lang.String.format("\\u%04x", (int) c));
            } else {
                out.append(c);
            }
        }
        return out.append('"').toString();
    }


    // 2026-11-19 (spec 2026-11-19-migration-http-parity-design.md, 1 "The request set", "Bounds"; RealWorld PR #24) -- the
    // request plan of the Factory's HTTP parity probe, derived from the application's handler mappings at runtime. This
    // source is COPIED into the generated FactoryHttpParityProbeTest (HttpParityProbe.planSource), which compiles in the
    // customer's build: java.* only, and Java 11 syntax (no records, switch expressions, text blocks or Stream.toList).
    // Order: the unknown path, the GraphQL requests (introspection, syntax error, GET; never a mutation), then the inventory
    // sorted by path pattern, then method: per GET a request without credentials; per POST/PUT/PATCH a malformed JSON body and
    // an empty object (rejected before any write); per pattern one method no mapping of that pattern allows. Path variables
    // and wildcards get a value that cannot exist. At most MAX_REQUESTS, the first in this order; DELETE is never sent to a
    // mapping that allows it.
    static final class HttpParityPlan {

        public static final int MAX_REQUESTS = 200;
        public static final java.lang.String MISSING = "factory-parity-missing";
        public static final java.lang.String UNKNOWN_PATH = "/factory-parity-unknown";
        public static final java.lang.String MALFORMED = "{\"factory-parity\":";
        public static final java.lang.String EMPTY_OBJECT = "{}";
        public static final java.lang.String INTROSPECTION = "{\"query\":\"{ __typename __schema { queryType { name } } }\"}";
        public static final java.lang.String SYNTAX_ERROR = "{\"query\":\"{ __typename \"}";
        private static final List<java.lang.String> SENT = List.of("GET", "POST", "PUT", "PATCH", "DELETE");
        private static final List<java.lang.String> NOT_ALLOWED_ORDER = List.of("PATCH", "PUT", "DELETE", "POST", "GET");

        /**
         * One path pattern of a handler mapping, the HTTP methods it allows (empty: every method) and whether its handler reads
         * a request body (a @RequestBody parameter). 2026-11-19 (HTTP parity review M1) -- a write handler that reads none
         * would run on any body, so it gets no request.
         */
        public static final class Mapping {
            public final java.lang.String pattern;
            public final Set<java.lang.String> methods;
            public final boolean readsBody;

            public Mapping(java.lang.String pattern, Set<java.lang.String> methods, boolean readsBody) {
                this.pattern = pattern;
                this.methods = Collections.unmodifiableSet(new TreeSet<java.lang.String>(methods == null ? Set.<java.lang.String>of() : methods));
                this.readsBody = readsBody;
            }

            /** A mapping whose handler reads a body. */
            public Mapping(java.lang.String pattern, Set<java.lang.String> methods) {
                this(pattern, methods, true);
            }
        }

        /**
         * One request: its case id ("METHOD pattern[ variant]"), the method, the concrete path, its variant (null: a plain
         * request) and the JSON body the variant sends (or null).
         */
        public static final class Request {
            public final java.lang.String caseId;
            public final java.lang.String method;
            public final java.lang.String path;
            public final java.lang.String variant;
            public final java.lang.String body;

            Request(java.lang.String caseId, java.lang.String method, java.lang.String path, java.lang.String body) {
                this.caseId = caseId;
                this.method = method;
                this.path = path;
                int space = caseId.indexOf(' ', caseId.indexOf(' ') + 1);
                this.variant = space < 0 ? null : caseId.substring(space + 1);
                this.body = body;
            }

            // 2026-11-19 (HTTP parity review C1) -- the request as one recorded line: case, method, path, variant ("-": none),
            // tab-separated (no field holds a tab or a line break: paths and case ids come from handler mapping patterns).
            public java.lang.String line() {
                return caseId + "\t" + method + "\t" + path + "\t" + (variant == null ? "-" : variant);
            }
        }

        // The body each request variant sends: only the two rejected-before-any-write bodies and the read-only GraphQL queries.
        static java.lang.String bodyOf(java.lang.String variant) {
            if (variant == null) {
                return null;
            }
            if ("malformed".equals(variant)) {
                return MALFORMED;
            }
            if ("empty-object".equals(variant)) {
                return EMPTY_OBJECT;
            }
            if ("graphql-introspection".equals(variant)) {
                return INTROSPECTION;
            }
            if ("graphql-syntax-error".equals(variant)) {
                return SYNTAX_ERROR;
            }
            return null;
        }

        /**
         * 2026-11-19 (HTTP parity review C1) -- the baseline's exact request list, as the Factory recorded it
         * (FactoryHttpParityRequests): replayed whole and in order on the candidate, never derived again (a framework-owned
         * mapping the candidate no longer has is still requested and compared). A malformed line is skipped.
         */
        public static List<Request> fromLines(java.lang.String[] lines) {
            List<Request> out = new ArrayList<Request>();
            Set<java.lang.String> seen = new LinkedHashSet<java.lang.String>();
            for (java.lang.String line : lines) {
                java.lang.String[] f = line == null ? new java.lang.String[0] : line.split("\t", -1);
                if (f.length != 4 || !f[2].startsWith("/") || !SENT.contains(f[1]) || !f[0].startsWith(f[1] + " ")) {
                    continue;
                }
                java.lang.String variant = "-".equals(f[3]) ? null : f[3];
                Request request = new Request(f[0], f[1], f[2], bodyOf(variant));
                if (variant == null ? request.variant == null : variant.equals(request.variant)) {
                    add(out, seen, request);
                }
            }
            return out;
        }

        private HttpParityPlan() {
        }

        public static List<Request> plan(List<Mapping> mappings, java.lang.String graphqlPath) {
            List<Request> out = new ArrayList<Request>();
            Set<java.lang.String> seen = new LinkedHashSet<java.lang.String>();
            add(out, seen, new Request("GET " + UNKNOWN_PATH, "GET", UNKNOWN_PATH, null));
            if (graphqlPath != null && graphqlPath.startsWith("/")) {
                add(out, seen, new Request("POST " + graphqlPath + " graphql-introspection", "POST", graphqlPath, INTROSPECTION));
                add(out, seen, new Request("POST " + graphqlPath + " graphql-syntax-error", "POST", graphqlPath, SYNTAX_ERROR));
                add(out, seen, new Request("GET " + graphqlPath + " graphql-get", "GET", graphqlPath, null));
            }
            // pattern -> every method some mapping of it allows ("*" for a mapping that allows all); pattern -> the methods
            // some mapping of it handles with a @RequestBody
            Map<java.lang.String, Set<java.lang.String>> byPattern = new TreeMap<java.lang.String, Set<java.lang.String>>();
            Map<java.lang.String, Set<java.lang.String>> readsBody = new TreeMap<java.lang.String, Set<java.lang.String>>();
            for (Mapping mapping : mappings) {
                if (mapping.pattern == null || !mapping.pattern.startsWith("/")) {
                    continue;
                }
                Set<java.lang.String> methods = byPattern.get(mapping.pattern);
                if (methods == null) {
                    methods = new TreeSet<java.lang.String>();
                    byPattern.put(mapping.pattern, methods);
                }
                if (mapping.methods.isEmpty()) {
                    methods.add("*");
                } else {
                    methods.addAll(mapping.methods);
                }
                if (mapping.readsBody) {
                    Set<java.lang.String> reading = readsBody.get(mapping.pattern);
                    if (reading == null) {
                        reading = new TreeSet<java.lang.String>();
                        readsBody.put(mapping.pattern, reading);
                    }
                    reading.addAll(mapping.methods);
                }
            }
            for (Map.Entry<java.lang.String, Set<java.lang.String>> entry : byPattern.entrySet()) {
                java.lang.String pattern = entry.getKey();
                Set<java.lang.String> allowed = entry.getValue();
                java.lang.String path = concrete(pattern);
                boolean any = allowed.contains("*");
                boolean sendable = any;
                for (java.lang.String method : SENT) {
                    sendable |= allowed.contains(method);
                }
                if (!sendable) {
                    continue; // HEAD, OPTIONS or TRACE only
                }
                for (java.lang.String method : SENT) {
                    if (!any && !allowed.contains(method) || any && !"GET".equals(method)) {
                        continue;
                    }
                    if ("GET".equals(method)) {
                        add(out, seen, new Request("GET " + pattern, "GET", path, null));
                    } else if (!"DELETE".equals(method) && readsBody.containsKey(pattern)
                            && readsBody.get(pattern).contains(method)) {
                        add(out, seen, new Request(method + " " + pattern + " malformed", method, path, MALFORMED));
                        add(out, seen, new Request(method + " " + pattern + " empty-object", method, path, EMPTY_OBJECT));
                    }
                }
                if (!any) {
                    for (java.lang.String method : NOT_ALLOWED_ORDER) {
                        if (!allowedOnPath(byPattern, path, method)) {
                            add(out, seen, new Request(method + " " + pattern + " not-allowed", method, path, null));
                            break;
                        }
                    }
                }
            }
            return out.size() <= MAX_REQUESTS ? out : new ArrayList<Request>(out.subList(0, MAX_REQUESTS));
        }

        // Some pattern matching the concrete path allows the method (or every method): the request would reach a handler.
        private static boolean allowedOnPath(Map<java.lang.String, Set<java.lang.String>> byPattern, java.lang.String path, java.lang.String method) {
            for (Map.Entry<java.lang.String, Set<java.lang.String>> entry : byPattern.entrySet()) {
                if (matches(entry.getKey(), path) && (entry.getValue().contains("*") || entry.getValue().contains(method))) {
                    return true;
                }
            }
            return false;
        }

        /** Whether a path pattern ({variable}, {variable:regex}, *, **) matches a concrete path, approximately as Spring does. */
        static boolean matches(java.lang.String pattern, java.lang.String path) {
            java.lang.StringBuilder regex = new java.lang.StringBuilder();
            int i = 0;
            while (i < pattern.length()) {
                char c = pattern.charAt(i);
                if (c == '{') {
                    int depth = 0;
                    int j = i;
                    for (; j < pattern.length(); j++) {
                        if (pattern.charAt(j) == '{') {
                            depth++;
                        } else if (pattern.charAt(j) == '}' && --depth == 0) {
                            break;
                        }
                    }
                    regex.append("[^/]+");
                    i = j + 1;
                } else if (pattern.startsWith("**", i)) {
                    regex.append(".*");
                    i += 2;
                } else if (c == '*') {
                    regex.append("[^/]*");
                    i++;
                } else {
                    regex.append(java.util.regex.Pattern.quote(java.lang.String.valueOf(c)));
                    i++;
                }
            }
            return java.util.regex.Pattern.matches(regex.toString(), path);
        }

        /**
         * 2026-11-19 (HTTP parity re-review, isolation) -- the request lines of the Factory's FactoryHttpParityRequests source
         * (one string literal per line, as HttpParityProbe.requestsSource writes them), read as text from the exact path the
         * Factory passes: never a class loaded by name. Any other line is ignored.
         */
        public static List<java.lang.String> readRequests(java.lang.String source) {
            List<java.lang.String> out = new ArrayList<java.lang.String>();
            java.util.regex.Pattern literal = java.util.regex.Pattern.compile("^\\s*\"((?:[^\"\\\\]|\\\\.)*)\",\\s*$");
            for (java.lang.String line : source.split("\n")) {
                java.util.regex.Matcher m = literal.matcher(line);
                if (m.matches()) {
                    out.add(unescape(m.group(1)));
                }
            }
            return out;
        }

        private static java.lang.String unescape(java.lang.String text) {
            java.lang.StringBuilder out = new java.lang.StringBuilder();
            for (int i = 0; i < text.length(); i++) {
                char c = text.charAt(i);
                if (c != '\\' || i + 1 >= text.length()) {
                    out.append(c);
                    continue;
                }
                char n = text.charAt(++i);
                if (n == 't') {
                    out.append('\t');
                } else if (n == 'n') {
                    out.append('\n');
                } else if (n == 'r') {
                    out.append('\r');
                } else if (n == 'u' && i + 4 < text.length()) {
                    out.append((char) java.lang.Integer.parseInt(text.substring(i + 1, i + 5), 16));
                    i += 4;
                } else {
                    out.append(n);
                }
            }
            return out.toString();
        }

        private static void add(List<Request> out, Set<java.lang.String> seen, Request request) {
            if (seen.add(request.caseId)) {
                out.add(request);
            }
        }

        // Every {variable} (a regex inside it may hold braces) and every * / ** segment part becomes MISSING.
        static java.lang.String concrete(java.lang.String pattern) {
            java.lang.StringBuilder out = new java.lang.StringBuilder();
            int i = 0;
            while (i < pattern.length()) {
                char c = pattern.charAt(i);
                if (c == '{') {
                    int depth = 0;
                    int j = i;
                    for (; j < pattern.length(); j++) {
                        if (pattern.charAt(j) == '{') {
                            depth++;
                        } else if (pattern.charAt(j) == '}' && --depth == 0) {
                            break;
                        }
                    }
                    out.append(MISSING);
                    i = j + 1;
                } else if (c == '*') {
                    while (i < pattern.length() && pattern.charAt(i) == '*') {
                        i++;
                    }
                    out.append(MISSING);
                } else {
                    out.append(c);
                    i++;
                }
            }
            return out.toString();
        }
    }
